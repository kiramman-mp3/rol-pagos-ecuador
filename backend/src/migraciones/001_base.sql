-- Esquema base: 3 tablas del enunciado + novedades (insumos manuales del mes).

CREATE TABLE IF NOT EXISTS empleados (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cedula        TEXT    NOT NULL UNIQUE,
    nombres       TEXT    NOT NULL,
    cargo         TEXT    NOT NULL,
    sueldo_base   DOUBLE PRECISION    NOT NULL CHECK (sueldo_base > 0),
    fecha_ingreso TEXT    NOT NULL,                 -- ISO: AAAA-MM-DD
    tipo_contrato TEXT    NOT NULL,
    activo        INTEGER NOT NULL DEFAULT 1
);

-- Horas extras, comisiones y descuentos que se digitan a mano cada mes.
CREATE TABLE IF NOT EXISTS novedades (
    empleado_id      INTEGER NOT NULL REFERENCES empleados(id) ON DELETE CASCADE,
    anio             INTEGER NOT NULL,
    mes              INTEGER NOT NULL,
    horas_50         DOUBLE PRECISION NOT NULL DEFAULT 0,
    horas_100        DOUBLE PRECISION NOT NULL DEFAULT 0,
    horas_nocturnas  DOUBLE PRECISION NOT NULL DEFAULT 0,
    comisiones       DOUBLE PRECISION NOT NULL DEFAULT 0,
    otros_descuentos DOUBLE PRECISION NOT NULL DEFAULT 0,
    PRIMARY KEY (empleado_id, anio, mes)
);

-- Un rol por mes; volver a generarlo lo reemplaza.
CREATE TABLE IF NOT EXISTS roles_cabecera (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anio              INTEGER NOT NULL,
    mes               INTEGER NOT NULL,
    generado_en       TEXT    NOT NULL,
    num_empleados     INTEGER NOT NULL,
    total_ingresos    DOUBLE PRECISION    NOT NULL,
    total_descuentos  DOUBLE PRECISION    NOT NULL,
    total_neto        DOUBLE PRECISION    NOT NULL,
    total_provisiones DOUBLE PRECISION    NOT NULL,
    total_costo       DOUBLE PRECISION    NOT NULL,
    UNIQUE (anio, mes)
);

-- Una fila por empleado. Guarda una "foto" (cédula, nombre, cargo, sueldo) para que
-- el historial no cambie si luego se edita o elimina al empleado.
CREATE TABLE IF NOT EXISTS roles_detalle (
    id                     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rol_id                 INTEGER NOT NULL REFERENCES roles_cabecera(id) ON DELETE CASCADE,
    empleado_id            INTEGER,
    cedula                 TEXT NOT NULL,
    nombres                TEXT NOT NULL,
    cargo                  TEXT NOT NULL,
    sueldo_base            DOUBLE PRECISION NOT NULL,
    fecha_ingreso          TEXT NOT NULL,
    dias_trabajados        INTEGER NOT NULL,
    meses_servicio         INTEGER NOT NULL,
    valor_hora             DOUBLE PRECISION NOT NULL,
    -- ingresos
    sueldo                 DOUBLE PRECISION NOT NULL,
    horas_50               DOUBLE PRECISION NOT NULL,
    horas_100              DOUBLE PRECISION NOT NULL,
    horas_nocturnas        DOUBLE PRECISION NOT NULL,
    valor_horas_50         DOUBLE PRECISION NOT NULL,
    valor_horas_100        DOUBLE PRECISION NOT NULL,
    valor_recargo_nocturno DOUBLE PRECISION NOT NULL,
    comisiones             DOUBLE PRECISION NOT NULL,
    total_ingresos         DOUBLE PRECISION NOT NULL,
    -- descuentos
    aporte_iess            DOUBLE PRECISION NOT NULL,
    base_ir_anual          DOUBLE PRECISION NOT NULL,
    ir_anual               DOUBLE PRECISION NOT NULL,
    impuesto_renta         DOUBLE PRECISION NOT NULL,
    otros_descuentos       DOUBLE PRECISION NOT NULL,
    total_descuentos       DOUBLE PRECISION NOT NULL,
    neto_pagar             DOUBLE PRECISION NOT NULL,
    -- provisiones / costo empleador
    decimo_tercero         DOUBLE PRECISION NOT NULL,
    decimo_cuarto          DOUBLE PRECISION NOT NULL,
    vacaciones             DOUBLE PRECISION NOT NULL,
    fondos_reserva         DOUBLE PRECISION NOT NULL,
    aporte_patronal        DOUBLE PRECISION NOT NULL,
    total_provisiones      DOUBLE PRECISION NOT NULL,
    costo_empleador        DOUBLE PRECISION NOT NULL
);
